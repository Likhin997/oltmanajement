/**
 * GENERATOR DINAMIS `#show running-config` ZTE C300 / C320
 * Menghasilkan output `#show running-config` lengkap yang 100% sinkron dengan database saat ini:
 * mencakup setiap ONU yang baru di-Add/Authorize, VLAN baru, Uplink VLAN Tagging, PPPoE, dan TR-069!
 */
export function buildLiveZteRunningConfig(
  db: SmartOltDatabaseState,
  oltId: number
): string {
  const olt = db.olts.find((o) => o.id === oltId) || db.olts[0];
  const oltVlans = db.vlans.filter((v) => v.olt_id === olt.id);
  const oltUplinks = db.uplink_ports.filter((u) => u.olt_id === olt.id);
  const oltOnus = db.onus
    .filter((o) => o.olt_id === olt.id && o.is_authorized && o.onu_index !== null)
    .sort((a, b) => a.port - b.port || (a.onu_index || 0) - (b.onu_index || 0));

  const extraVlanNums = oltVlans
    .map((v) => v.vlan_id)
    .filter((v) => ![1, 41, 42, 43, 44, 46, 100, 101, 102].includes(v))
    .sort((a, b) => a - b);

  const lines: string[] = [
    `#show running-config`,
    `Building configuration...`,
    `olleh`,
    `timestamp_write: 17:36:50 11/10/2026`,
    `config-version 2.1`,
    `!`,
    `crtv disable`,
    `!`,
    `load-balance disable`,
    `!`,
    `operator-mode NORMAL`,
    `!`,
    `system-forwarding-mode normal-mode`,
    `!`,
    `set-pnp enable`,
    `add-rack rackno 1 racktype IEC19`,
    `add-shelf rackno 1 shelfno 1 shelftype IEC_SHELF`,
    `add-card rackno 1 shelfno 1 slotno 3 GTGH`,
    `add-card rackno 1 shelfno 1 slotno 19 HUVQ`,
    `!`,
    `eth-switch max-frame-length  1600`,
    `!`,
    `gpon`,
    `  profile tcont GPON-1G type 5 fixed 64 assured 64 maximum 1000192`,
    `  profile tcont SMARTOLT-VOIPMNG-10M type 5 fixed 512 assured 1024 maximum 11264`,
    `  profile tcont SMARTOLT-IPTV-10M-UP type 5 fixed 512 assured 1024 maximum 11264`,
    `  profile tcont SMARTOLT-1G-UP type 5 fixed 128 assured 1024 maximum 1048064`,
    `  profile traffic SMARTOLT-VOIPMNG-10M sir 10480 pir 11264`,
    `  profile traffic SMARTOLT-IPTV-50M-DOWN sir 56320 pir 56320`,
    `  profile traffic SMARTOLT-1G-DOWN sir 1048064 pir 1048064 cbs 1023 pbs 1023`,
    `!`,
    `gpon`,
    `  onu profile vlan SMARTOLT-vlan1011 tag-mode tag cvlan 1011`,
    `  onu profile vlan SMARTOLT-vlan100 tag-mode tag cvlan 100`,
  ];

  for (const v of oltVlans) {
    if (v.vlan_id !== 100 && v.vlan_id !== 1011) {
      lines.push(
        `  onu profile vlan SMARTOLT-vlan${v.vlan_id} tag-mode tag cvlan ${v.vlan_id}`
      );
    }
  }

  lines.push(
    `!`,
    `pon`,
    `  onu-type ALL gpon`,
    `  onu-type ALL gpon max-tcont 8`,
    `  onu-type ALL gpon max-gemport 32`,
    `  onu-type ALL gpon max-switch-perslot 8`,
    `  onu-type ALL gpon max-flow-perswitch 8`,
    `  onu-type ALL gpon max-iphost 5`,
    `  onu-type F670LV9.0 gpon`,
    `  onu-type F670LV9.0 gpon max-tcont 8`,
    `  onu-type F670LV9.0 gpon max-gemport 32`,
    `  onu-type F670LV9.0 gpon max-switch-perslot 8`,
    `  onu-type F670LV9.0 gpon max-flow-perswitch 8`,
    `  onu-type F670LV9.0 gpon max-iphost 5`,
    `  uncfg-onu-display-info model sn pw`,
    `!`,
    `vlan database`,
    `  vlan 1,41-44,46,100-102`,
    `  vlan ${extraVlanNums.length > 0 ? extraVlanNums.join(',') : '111,120,140,1011'}`,
    `!`
  );

  for (const v of oltVlans) {
    if (v.name) {
      lines.push(`vlan ${v.vlan_id}`, `  name ${v.name}`, `!`);
    }
  }

  lines.push(
    `interface mng1`,
    `  ip address 136.1.1.100 255.255.0.0`,
    `  config-filename startrun.dat`,
    `  negotiation auto`,
    `  tag-mode untag`,
    `!`,
    `interface vlan 102`,
    `  ip address ${olt.ip_address} 255.255.255.252`,
    `!`
  );

  // Per-port GPON OLT + GPON ONU interfaces (Ports 1..16)
  for (let p = 1; p <= 16; p++) {
    const portOnus = oltOnus.filter((o) => o.port === p);
    lines.push(`interface gpon-olt_1/3/${p}`, `  no shutdown`, `  linktrap disable`);
    for (const o of portOnus) {
      const zType = o.onu_type === 'F670LV9.0' ? 'F670LV9.0' : 'ALL';
      lines.push(`  onu ${o.onu_index} type ${zType} sn ${o.serial_number}`);
    }
    lines.push(`!`);

    for (const o of portOnus) {
      const vlObj = db.vlans.find((v) => v.id === o.vlan_id);
      const vlanNum = vlObj?.vlan_id || 101;
      lines.push(
        `interface gpon-onu_1/3/${p}:${o.onu_index}`,
        `  name ${o.customer_name || o.serial_number}`,
        `  description ${o.address || 'none'}`,
        `  sn-bind enable sn`,
        `  tcont 1 profile SMARTOLT-1G-UP`
      );
      if (o.config_method === 'TR069') {
        lines.push(`  tcont 2 profile SMARTOLT-VOIPMNG-10M`);
      }
      lines.push(
        `  gemport 1 tcont 1`,
        `  gemport 1 traffic-limit downstream SMARTOLT-1G-DOWN`
      );
      if (o.config_method === 'TR069') {
        lines.push(
          `  gemport 2 tcont 2`,
          `  gemport 2 traffic-limit downstream SMARTOLT-VOIPMNG-10M`
        );
      }
      lines.push(`  service-port 1 vport 1 user-vlan ${vlanNum} vlan ${vlanNum}`);
      if (o.config_method === 'TR069') {
        lines.push(`  service-port 2 vport 2 user-vlan 100 vlan 100`);
      }
      lines.push(`!`);
    }
  }

  // Uplink Interfaces
  for (const u of oltUplinks) {
    const is10G = u.name.startsWith('xgei');
    const cleanTag = u.tagged_vlans.replace(/^(Hybrid|Trunk|Access):\s*/i, '').trim() || '102';
    lines.push(`interface ${u.name}`);
    if (is10G) lines.push(`  phy-attribute lan`);
    lines.push(
      u.admin_state === 'Enabled' ? `  no shutdown` : `  shutdown`,
      `  hybrid-attribute fiber`,
      is10G ? `  no negotiation auto` : `  negotiation auto`
    );
    if (is10G) lines.push(`  speed 10000`, `  duplex full`);
    lines.push(
      `  flowcontrol disable`,
      `  linktrap enable`,
      `  switchport mode hybrid`,
      `  switchport default vlan ${u.pvid_untag}`,
      `  switchport vlan ${cleanTag} tag`,
      `  port-protect disable`,
      `  uplink-isolate disable`,
      `!`
    );
  }

  lines.push(`ip route 0.0.0.0 0.0.0.0 172.16.0.1`, `!`, `pon`, `!`);

  // Per-ONU OMCI `pon-onu-mng` blocks
  for (const o of oltOnus) {
    const vlObj = db.vlans.find((v) => v.id === o.vlan_id);
    const vlanNum = vlObj?.vlan_id || 101;
    const trProfile =
      db.tr069_profiles.find((t) => t.id === o.tr069_profile_id) ||
      db.tr069_profiles[0];

    lines.push(`pon-onu-mng gpon-onu_1/3/${o.port}:${o.onu_index}`);
    if (o.config_method === 'TR069') {
      lines.push(
        `  voip protocol sip`,
        `  flow 2 switch switch_0/1`,
        `  flow mode 1 tag-filter vlan-filter untag-filter discard`,
        `  flow mode 2 tag-filter vlan-filter untag-filter discard`,
        `  flow 1 pri 0 vlan ${vlanNum}`,
        `  flow 2 pri 2 vlan 100`,
        `  gemport 1 flow 1`,
        `  gemport 2 flow 2`,
        `  switchport-bind switch_0/1 iphost 1`,
        `  switchport-bind switch_0/1 iphost 2`,
        `  switchport-bind switch_0/1 veip 1`
      );
      if (o.wan_mode === 'PPPOE' && o.pppoe_username) {
        lines.push(
          `  pppoe 1 nat enable user ${o.pppoe_username} password ${o.pppoe_password || 'jetcyber'}`
        );
      }
      lines.push(
        `  ip-host 2 dhcp-enable enable ping-response enable traceroute-response enable`,
        `  vlan-filter-mode iphost 1 tag-filter vlan-filter untag-filter discard`,
        `  vlan-filter-mode iphost 2 tag-filter vlan-filter untag-filter discard`,
        `  vlan-filter iphost 1 pri 0 vlan ${vlanNum}`,
        `  vlan-filter iphost 2 pri 2 vlan 100`
      );
    } else {
      lines.push(
        `  flow mode 1 tag-filter vlan-filter untag-filter discard`,
        `  flow 1 pri 0 vlan ${vlanNum}`
      );
      if (o.hotspot_bridge_vlan) {
        lines.push(`  flow 1 pri 0 vlan ${o.hotspot_bridge_vlan}`);
      }
      lines.push(
        `  gemport 1 flow 1`,
        `  switchport-bind switch_0/1 iphost 1`,
        `  switchport-bind switch_0/1 veip 1`,
        `  pppoe 1 nat enable user ${o.pppoe_username || o.customer_name || 'USER'} password ${o.pppoe_password || 'jetcyber'}`,
        `  vlan-filter-mode iphost 1 tag-filter vlan-filter untag-filter discard`,
        `  vlan-filter iphost 1 pri 0 vlan ${vlanNum}`
      );
    }

    const ethPorts = o.onu_type === 'F670LV9.0' ? 4 : 8;
    for (let e = 1; e <= ethPorts; e++) {
      lines.push(`  dhcp-ip ethuni eth_0/${e} from-onu`);
    }

    if (o.config_method === 'TR069') {
      lines.push(
        `  veip 1 port udp 1232 host 2`,
        `  tr069-mgmt 1 state unlock`,
        `  tr069-mgmt 1 acs ${trProfile.acs_url} validate basic username ${trProfile.acs_username} password ${trProfile.acs_password}`,
        `  tr069-mgmt 1 tag pri 2 vlan 100`
      );
    }

    lines.push(`  security-mgmt 1 state enable mode forward protocol web https`);
    if (o.wan_remote_access === 'Enabled only from NOC subnet') {
      const allowedIp = o.wan_remote_allowed_subnet || '10.69.69.1';
      lines.push(
        `  security-mgmt 10 state enable mode forward protocol web https`,
        `  security-mgmt 10 start-src-ip ${allowedIp} end-src-ip ${allowedIp}`
      );
    }
    lines.push(
      `  security-mgmt 998 state enable mode forward ingress-type lan protocol web https`,
      `  security-mgmt 999 state enable ingress-type lan protocol ftp telnet ssh snmp tr069`,
      `!`
    );
  }

  lines.push(
    `snmp-server community JCN_Read view allview ro`,
    `snmp-server community JCN_Write view allview rw`,
    `snmp-server host 10.69.69.1 version 2c st26c3f4ob2fe6b2207bb77a05 enable NOTIFICATIONS target-addr-name smartolt udp-port 162`,
    `!`,
    `ntp server 20.101.57.9 priority 1 version 4`,
    `ntp server 216.239.35.4 priority 2 version 4`,
    `ntp server 162.159.200.123 priority 3 version 4`,
    `!`,
    `end`
  );

  return lines.join('\n');
}

